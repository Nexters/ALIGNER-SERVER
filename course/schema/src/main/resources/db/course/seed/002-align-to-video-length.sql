-- 모든 스텝을 **30 초 × N 세트**로 맞춘다. 30 초는 YMove 영상 길이다.
--
-- 2026-08-19 에 29 개 slug 를 전부 실측했고 **예외 없이 30.0 초**였다. YMove 응답의
-- `videoDurationSecs` 는 29 개 모두 null 이라 쓸 수 없어, HLS 플레이리스트(`videoHlsUrl`)의
-- `#EXTINF` 합으로 쟀다. 요가 영상이 자세를 한 번 보여주는 시연 루프이기 때문이다.
--
-- **한 세트 = 영상 1 회**가 된다. 재생이 자세 시연과 정확히 맞물리고, 세트 수가 곧 반복
-- 횟수라 플레이어가 배속·자름 없이 그대로 튼다.
--
-- 001-course-template.sql 은 정본 표기를 그대로 옮겨 준비 자세가 90·120·150 초 1 세트,
-- 핀포즈가 "30 초 × 3" 같은 형태였다. 총 시간(duration × set)은 그대로 두고 단위만 30 초로
-- 쪼개므로 **루틴 길이는 15 분 / 17 분 30 초 / 20 분 그대로다.**
--
--   준비 자세  90 → 30×3    120 → 30×4    150 → 30×5     (전부 30 의 배수라 딱 떨어진다)
--   핀포즈     30×3 · 30×4  그대로        40×3 → 30×4    35×3 → 30×4
--
-- **보트자세만 딱 떨어지지 않는다.** 정본이 35 초 × 3 = 105 초인데 30 으로 나누면 3.5 다.
-- 반올림해 4 세트(120 초)로 올렸다. 내리면 90 초가 되어 레벨 1 핀포즈(반 보트 90 초)와
-- 같아져 레벨 2 가 더 쉬워지지 않는다. 15 초가 늘지만 도전 강도의 순서는 지킨다.
--
-- **낙타자세·브릿지·말라사나·보트자세는 한 세트 유지 시간이 짧아진다** (40·35 → 30 초).
-- 총 시간은 같고 세트가 늘어난 것이라 운동량은 유지되지만, 한 번에 버티는 시간이 줄어
-- 정본보다 쉬워진다. 감수가 이 넷을 되돌리려면 30 의 배수로 다시 받아야 한다.
--
-- 총 시간을 보존하므로 catalog seed/010 의 MET 루틴 가중평균 검산도 그대로 유효하다.

UPDATE course.template_step_exercise
   SET set_count = ROUND(duration_seconds * COALESCE(set_count, 1) / 30.0)::SMALLINT,
       duration_seconds = 30;

-- 이미 만들어진 회원 코스도 맞춘다. course_step_exercise 는 코스 생성 시점에 템플릿에서
-- 복사되므로(course/model/Course.kt) 템플릿만 고치면 기존 코스가 옛 시간으로 남는다.
UPDATE course.course_step_exercise
   SET set_count = ROUND(duration_seconds * COALESCE(set_count, 1) / 30.0)::SMALLINT,
       duration_seconds = 30;
