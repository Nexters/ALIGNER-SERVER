-- 진단 1 회. 애그리거트 루트다.
--
-- perceived_body_part_code 는 회원이 고른 "느끼는 부위" 다. 판별된 "원인 부위" 는
-- screening_cause 가 갖는다. 둘을 한 컬럼에 섞으면 AGENTS.md §1 의
-- "느끼는 부위가 아니라 원인 부위를 처방한다" 가 스키마에서 사라진다.
--
-- member_id 는 값 컬럼이고 FK 가 없다 (docs/architecture.md §6).
CREATE TABLE screening.screening_result (
    result_id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id                BIGINT      NOT NULL,
    perceived_body_part_code VARCHAR(40) NOT NULL,
    created_at               TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_screening_result_body_part FOREIGN KEY (perceived_body_part_code)
        REFERENCES screening.body_part (body_part_code)
);

-- 최신 결과 조회가 회원으로 걸러 created_at 내림차순으로 하나를 집는다.
CREATE INDEX ix_screening_result_member_created
    ON screening.screening_result (member_id, created_at DESC);

COMMENT ON TABLE screening.screening_result IS '진단 1 회. 회원은 여러 번 다시 진단할 수 있다';
COMMENT ON COLUMN screening.screening_result.member_id IS 'member.member 의 값이지만 도메인 간 FK 는 걸지 않는다';
COMMENT ON COLUMN screening.screening_result.perceived_body_part_code IS '회원이 고른 부위. 진단의 입력이자 맥락이고 판별 결과가 아니다';
