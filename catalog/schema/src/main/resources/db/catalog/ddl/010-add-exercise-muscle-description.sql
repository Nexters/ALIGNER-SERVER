-- 운동 가이드의 「핵심 동작」 문구를 근육 매핑에 붙인다.
--
-- 화면이 근육맵에서 근육을 칠하고 그 옆 카드에 한 문장을 그린다. 문구의 주어가 근육이므로
-- 자리도 근육 매핑이다 — (운동, 부위) 별도 테이블로 두면 같은 탭의 근육 셋이 문장 하나를
-- 나눠 갖게 되어, 어느 근육을 짚어도 같은 설명이 나온다.
--
-- exercise_voice_cue 와 자리가 다르다. 저쪽은 재생 타임라인 대본이라 start_offset_seconds 를
-- 갖고, 이쪽은 재생 전 정적 설명이다. 문구를 지시사항에서 뽑아 쓰더라도 저장은 독립적으로
-- 한다 — 대본이 감수로 바뀔 때 핵심 동작이 같이 흔들리면 안 된다.
--
-- NULL 을 허용한다. 감수 전 데이터라 문구가 아직 없는 근육이 있을 수 있고, 그때는 화면이
-- 카드를 그리지 않는다. NOT NULL 로 두면 근육 매핑을 넣는 데 문구가 선행 조건이 된다.
--
-- pose_muscle 에는 넣지 않는다. 자세 상세를 그리는 화면이 아직 없어 소비자가 없다.
ALTER TABLE catalog.exercise_muscle
    ADD COLUMN description TEXT;

COMMENT ON COLUMN catalog.exercise_muscle.description IS
    '운동 가이드의 핵심 동작 한 문장. 이 운동에서 그 근육을 어떻게 쓰는지다. 감수 대상이라 NULL 을 허용한다';
