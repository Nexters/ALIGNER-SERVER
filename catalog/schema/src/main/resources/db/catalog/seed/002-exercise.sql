--
-- **핀포즈도 여기 들어온다.** 핀포즈는 target_pose 와 exercise 양쪽에 행을 갖는다
-- (docs/domains.md §4-3). 코스의 목표이면서 동시에 마지막 스텝으로 재생되기 때문이다.
--
-- exercise_id 는 정본 §10 의 순번 + 100 이다. 대역을 맞춰 두면 seed 를 정본과 나란히 놓고
-- 대조할 수 있고, target_pose_id(1~9)와 겹치지 않아 course_step_exercise.exercise_id 를 읽을 때
-- 어느 쪽 식별자인지 눈으로 구분된다.
--
-- **좌우로 나뉘는 자세도 한 행이다.** 정본이 `cow-face-pose-*` 처럼 한 자세로 세고 루틴 표도
-- 한 스텝(예: `소 얼굴 자세 (좌/우) · 2분`)으로 배치한다. **YMove 의 exercise 단위는 좌우가
-- 갈린 37 개**라 이 29 행과 1:1 이 아니고, 그 정합은 YMove 연동에서 맞춘다
-- (docs/domains.md §7-6). 지금 나누지 않는 것은 정본이 한 스텝의 2 분을 좌우로 어떻게
-- 나누는지 주지 않아서다 — 나누려면 없는 값을 지어내야 한다.
--
-- **음성 큐(exercise_voice_cue)를 함께 넣지 않는 이유도 같다.** 대본은 YMove exercise 단위라
-- 좌우가 갈리는데, 정본의 호랑이 자세는 오른쪽 기준(`오른쪽 다리를 뒤로 들어…`)이고
-- 파이어로그는 왼쪽 기준이다. 29 행에 매달면 반대쪽을 수행할 때 틀린 지시를 읽어준다.
-- 영상(video_url)이 없어 세션 플레이어가 아직 돌지 않으므로 함께 미룬다.
--
-- caution_note 는 정본의 자세별 주의사항이고, 핀포즈에는 그 루틴의 주의사항이 뒤에 붙는다.
-- **사용자에게 그대로 읽히는 안전 문구라 한 글자도 바꾸지 않는다.** 업독의 루틴 주의사항은
-- 원본에서 취소선 처리돼 있어 넣지 않았다.
--
-- 아래 컬럼은 아직 비운다. 확정되는 대로 UPDATE changeset 을 새로 쌓는다.
--   met_value                — 정본이 MET 을 루틴 단위(2.3·2.8·3.0)로 주는데 이 컬럼은 운동 단위다 (§7-10)
--   default_duration_seconds — 같은 자세가 루틴마다 시간이 다르다. 실제 값은 template_step_exercise 에 있다
--   difficulty               — 우리가 부여해야 한다
--   ymove_slug / video_url   — YMove 연동 후 (docs/domains.md §7-4·5·6)
--
-- category 는 코스 개요가 운동 이름 아래 그리는 분류다. 정본의 "중점" 에 웜업이라고 적힌
