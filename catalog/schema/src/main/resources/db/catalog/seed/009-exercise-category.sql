-- 002-exercise.sql 이 비워둔 category 18 개를 채운다.
--
-- **감수 전 임시값이다.** 007-split-muscle-highlight-and-add-exercise-category.sql 이
-- "분류 어휘가 확정되면 그때 CHECK 을 얹는다" 고 적었는데, 확정이 아니라 화면을 막지 않으려고
-- 우리가 부여한 값이라 **CHECK 을 걸지 않는다.** 감수가 어휘를 주면 UPDATE 를 새로 쌓고
-- 그때 CHECK 을 붙인다.
--
-- 어휘는 4 개다. 기존 두 값(`가동성 웜업`·`핀포즈`)에 `유연성`·`근력 강화` 를 더했다.
-- 기존 값 자체가 이미 "물리 분류 + 구조 역할" 이 섞인 어휘라 결에 맞췄다.
--
-- 판정 근거는 docs/context/routine-content.md 의 자세 블록마다 붙은 `중점` 줄이고,
-- 규칙은 하나다 — **중점이 신장·가동범위·이완이면 `유연성`, 등척성·안정·활성이면 `근력 강화`.**
-- catalog.exercise_muscle 의 STRETCH / STRENGTHEN 비중도 같은 방향인지 대조했다.
--
-- 후굴 계열이 판정이 갈리는 자리다. 스핑크스·코브라는 척추기립근이 주동이지만 정본이
-- "가장 얕은 후굴" 이라 적었고 준비 자세로 쓰이므로 `유연성` 으로 뒀다. 반대로 활 자세는
-- 주동근 3 개(척추기립근·대둔근·햄스트링)가 신장근과 같은 수라 `근력 강화` 다.
-- **이 다섯 개가 감수에서 가장 먼저 뒤집힐 후보다.**
--
-- 101·113 은 정본에 "(웜업)" 표기가 있어 이미 `가동성 웜업` 이고, 핀포즈 9 개도 이미 값이
-- 있어 여기서 건드리지 않는다.

-- 유연성 14 개 — 중점이 신장·가동범위·이완이다.
UPDATE catalog.exercise SET category = '유연성'
 WHERE exercise_id IN (
        102,  -- 스핑크스 자세    요추~흉추 하부 신전 (가장 얕은 후굴)
        103,  -- 소 얼굴 자세     견관절 외회전+굴곡 / 내회전+신전, 근육 전부 STRETCH
        105,  -- 코브라 자세      흉추·요추 신전, 복직근 신장
        107,  -- 퍼피 자세        흉추 신전 + 견관절 굴곡 가동범위, 근육 전부 STRETCH
        108,  -- 로우 런지        고관절 굴곡근 신장
        115,  -- 앉은 전굴 자세   후방 사슬 신장
        118,  -- 문 빗장 자세     측면 사슬(체간 외측) 신장
        119,  -- 반 물고기의 왕   흉추 회전 + 대둔근·이상근 신장
        121,  -- 누운 나비 자세   고관절 외회전·외전 수동 이완
        122,  -- 해피 베이비      고관절 굴곡 가동범위 + 요추 이완
        123,  -- 누운 비둘기      심부 외회전근 이완
        124,  -- 다운독           발목 배측굴곡 + 후방 사슬 신장
        125,  -- 나비 자세        고관절 외회전 + 내전근 신장
        126   -- 개구리 자세      고관절 외전 + 내전근 심화 신장
       );

-- 근력 강화 4 개 — 중점이 등척성·안정·활성이다.
UPDATE catalog.exercise SET category = '근력 강화'
 WHERE exercise_id IN (
        104,  -- 호랑이 자세      단측 지지 항회전 안정 + 고관절 신전
        111,  -- 활 자세          전신 후굴 + 어깨 신전, 주동근이 신장근과 같은 수다
        114,  -- 플랭크 자세      코어 등척성 + 견갑 안정
        127   -- 의자 자세        하체 등척성 근력 + 발목 배측굴곡
       );
