 WHERE exercise_id IN (
        111,  -- 활 자세          전신 후굴 근력
        112,  -- 휠               핀포즈 · 등 라인 레벨 3
        120,  -- 사이드 플랭크    핀포즈 · 복부 라인 레벨 3
        126,  -- 개구리 자세      고관절 심화 신장, 주의사항에 중단 신호가 있다
        129   -- 파이어로그       핀포즈 · 골반 라인 레벨 3
       );
