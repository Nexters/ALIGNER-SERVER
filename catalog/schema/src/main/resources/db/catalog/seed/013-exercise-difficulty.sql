-- 002-exercise.sql 이 감수 대기로 비워둔 difficulty 를 29 개 전부 채운다.
--
-- **감수 전 임시값이다.** 001-create-exercise.sql 이 "우리가 감수로 부여한다. 값 집합이
-- 미정이라 CHECK 을 걸지 않았다" 고 적은 그 컬럼이고, 여기서도 CHECK 을 얹지 않는다.
-- 화면이 null 때문에 난이도 배지를 못 그리는 상태를 먼저 푸는 것이 목적이다.
--
-- 어휘는 `EASY` / `MEDIUM` / `HARD` 세 개다. category 와 달리 한글이 아니라 대문자 영문인
-- 것은 프론트가 배지 색을 값으로 분기하기 때문이다 — 표시 문구는 프론트가 만든다.
--
-- 배정 규칙은 두 가지다.
--
--   1. 핀포즈 9 개는 정본(docs/context/routine-content.md §10)의 루틴 레벨을 그대로 쓴다.
--      레벨 1 → EASY, 2 → MEDIUM, 3 → HARD. 핀포즈가 그 루틴의 목표 자세라 레벨이 곧
--      그 자세의 난이도다.
--   2. 나머지 20 개는 010-exercise-met-value.sql 의 MET 배정과 같은 축(수동 신장 → 등척성
--      유지 → 전신 부하)에 자세별 주의사항 강도를 얹었다. MET 과 완전히 같지는 않다 —
--      MET 은 에너지 소비이고 난이도는 관절 가동범위 요구까지 포함하기 때문이다.
--      소 얼굴 자세(MET 2.3)가 MEDIUM 인 것이 그 자리다.

-- EASY 14 개 — 수동 신장·웜업·레벨 1 핀포즈.
UPDATE catalog.exercise SET difficulty = 'EASY'
 WHERE exercise_id IN (
        101,  -- 고양이-소 자세   동적 웜업
        102,  -- 스핑크스 자세    가장 얕은 후굴
        105,  -- 코브라 자세      팔 지지 얕은 후굴
        106,  -- 업독             핀포즈 · 등 라인 레벨 1
        107,  -- 퍼피 자세        수동 신장
        108,  -- 로우 런지        하지 지지 신장
        109,  -- 브릿지           핀포즈 · 골반 라인 레벨 1
        113,  -- 누워서 와이퍼    누운 동적 웜업
        116,  -- 반 보트          핀포즈 · 복부 라인 레벨 1
        118,  -- 문 빗장 자세     측면 수동 신장
        121,  -- 누운 나비 자세   수동 이완
        122,  -- 해피 베이비      수동 이완
        123,  -- 누운 비둘기      수동 이완
        125   -- 나비 자세        앉은 수동 신장
       );

-- MEDIUM 10 개 — 등척성 유지·가동범위 요구·레벨 2 핀포즈.
UPDATE catalog.exercise SET difficulty = 'MEDIUM'
 WHERE exercise_id IN (
        103,  -- 소 얼굴 자세     견관절 가동범위 요구가 커서 MET 대비 올렸다
        104,  -- 호랑이 자세      단측 지지 항회전 안정
        110,  -- 낙타자세         핀포즈 · 등 라인 레벨 2
        114,  -- 플랭크 자세      코어 등척성
        115,  -- 앉은 전굴 자세   햄스트링 가동범위 요구
        117,  -- 보트자세         핀포즈 · 복부 라인 레벨 2
        119,  -- 반 물고기의 왕   흉추 회전
        124,  -- 다운독           전신 지지 + 발목 배측굴곡
        127,  -- 의자 자세        하체 등척성
        128   -- 말라사나         핀포즈 · 골반 라인 레벨 2
       );

-- HARD 5 개 — 전신 후굴·심화 신장·레벨 3 핀포즈.
